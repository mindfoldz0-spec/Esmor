#!/usr/bin/env node
/* global __dirname, Buffer */
/**
 * One-time migration: converts src/constants/pregenerated-voices.json
 * (base64 WAVs embedded in the JS bundle) into individual binary assets
 * under assets/voices/, and regenerates src/constants/pregenerated-voice-assets.ts
 * with static require() calls.
 *
 * Safe to re-run; it overwrites whatever already exists in assets/voices/.
 */
const fs = require('fs');
const path = require('path');

const PROJECT_ROOT = path.resolve(__dirname, '..');
const JSON_PATH = path.join(PROJECT_ROOT, 'src', 'constants', 'pregenerated-voices.json');
const ASSETS_DIR = path.join(PROJECT_ROOT, 'assets', 'voices');
const MANIFEST_PATH = path.join(PROJECT_ROOT, 'src', 'constants', 'pregenerated-voice-assets.ts');

function voiceIdToFileName(voiceId) {
  return `${voiceId.replace(/[^a-zA-Z0-9]/g, '_')}.wav`;
}

function writeManifest(ids) {
  const sorted = [...ids].sort();
  const lines = sorted.map(
    (id) => `  ${JSON.stringify(id)}: require('@/assets/voices/${voiceIdToFileName(id)}'),`
  );

  const manifest = `// Generated by scripts/decode-voices.js - do not edit by hand.
// Bundled voice prompts decoded from pregenerated-voices.json into binary assets.
// Keys are "{language}:{voiceKey}", matching the cache ids used by the voice services.
export const PREGENERATED_VOICE_ASSETS: Record<string, number> = {
${lines.join('\n')}
};
`;

  fs.writeFileSync(MANIFEST_PATH, manifest, 'utf8');
}

function main() {
  if (!fs.existsSync(JSON_PATH)) {
    console.error(`No ${JSON_PATH} found. Nothing to decode.`);
    process.exit(1);
  }

  const json = JSON.parse(fs.readFileSync(JSON_PATH, 'utf8'));
  fs.mkdirSync(ASSETS_DIR, { recursive: true });

  let bytes = 0;
  const ids = [];

  for (const [voiceId, entry] of Object.entries(json)) {
    const fileName = voiceIdToFileName(voiceId);
    const buffer = Buffer.from(entry.audioBase64, 'base64');
    fs.writeFileSync(path.join(ASSETS_DIR, fileName), buffer);
    bytes += buffer.length;
    ids.push(voiceId);
  }

  writeManifest(ids);

  console.log(`Decoded ${ids.length} voice clips (${(bytes / 1024 / 1024).toFixed(1)} MB) into assets/voices/`);
  console.log(`Manifest written to ${MANIFEST_PATH}`);
}

main();
